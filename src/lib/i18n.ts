const dict = { sv, en } as const;
export type TKey = keyof typeof sv;

export function translate(lang: Lang, k: TKey, vars?: Record<string, string | number>): string {
  let s = (dict[lang] as any)[k] ?? sv[k] ?? k;
  if (vars) for (const [key, v] of Object.entries(vars)) s = s.replaceAll(`{${key}}`, String(v));
  return s;
}

export function useLang(): Lang {
  const [lang, setLangState] = useState<Lang>(getLang());
  useEffect(() => {
    const h = () => setLangState(getLang());
    window.addEventListener("stipendia:lang", h);
    return () => window.removeEventListener("stipendia:lang", h);
  }, []);
  return lang;
}

export function useT() {
  const lang = useLang();
  return (k: TKey, vars?: Record<string, string | number>) => translate(lang, k, vars);
}

export function optionLabel(lang: Lang, value: string): string {
  return optionLabels[value]?.[lang] ?? value;
}

export function useOptionLabel() {
  const lang = useLang();
  return (value: string) => optionLabel(lang, value);
}
